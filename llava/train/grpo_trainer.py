def split_tensor_dict(
    tensor_dict: dict[str, Optional[torch.Tensor]], num_chunks: int
) -> list[dict[str, Optional[torch.Tensor]]]:
    """
    Splits a dictionary of tensors along the first dimension into `num_chunks` equal parts.

    Example:
        >>> x = torch.arange(12).reshape(6, 2)
        >>> y = torch.arange(6).reshape(6, 1)
        >>> tensor_dict = {"x": x, "y": y}
        >>> split_tensor_dict(tensor_dict, 3)
        [
            {"x": tensor([[0, 1], [2, 3]]), "y": tensor([[0], [1]])},
            {"x": tensor([[4, 5], [6, 7]]), "y": tensor([[2], [3]])},
            {"x": tensor([[ 8,  9], [10, 11]]), "y": tensor([[4], [5]])}
        ]
    """
    multimodal_inputs = tensor_dict.pop('multimodal_inputs', None)
    first_tensor = next(tensor for tensor in tensor_dict.values() if tensor is not None)
    chunk_size = first_tensor.shape[0] // num_chunks
    # return [
    #     {
    #         key: tensor[i * chunk_size : (i + 1) * chunk_size] if tensor is not None else None
    #         for key, tensor in tensor_dict.items()
    #     }
    #     for i in range(num_chunks)
    # ]

    # handle list objects
    output_list = []
    for i in range(num_chunks):
        output_dict = {}
        for key, tensor in tensor_dict.items():
            if tensor is None:
                output_dict[key] = None
            else:
                output_dict[key] = tensor[i * chunk_size : (i + 1) * chunk_size]
        
        if multimodal_inputs is not None:
            split_multimodal_inputs = {}
            for mm_key, mm_tensor in multimodal_inputs.items():
                if mm_tensor is None:
                    split_multimodal_inputs[mm_key] = None
                else:
                    split_multimodal_inputs[mm_key] = mm_tensor[i * chunk_size : (i + 1) * chunk_size]
            output_dict['multimodal_inputs'] = split_multimodal_inputs
        
        output_list.append(output_dict)
        
    return output_list


def shuffle_tensor_dict(tensor_dict: dict[str, Optional[torch.Tensor]]) -> dict[str, Optional[torch.Tensor]]:
    """
    Shuffles a dictionary of tensors along the first dimension in unison.

    Example:
        >>> x = torch.arange(6).reshape(3, 2)
        >>> y = torch.arange(3).reshape(3, 1)
        >>> tensor_dict = {"x": x, "y": y}
        >>> shuffle_tensor_dict(tensor_dict)
        {'x': tensor([[2, 3],
                      [0, 1],
                      [4, 5]]),
         'y': tensor([[1],
                      [0],
                      [2]])}
    """
    multimodal_inputs = tensor_dict.pop('multimodal_inputs', None)
    first_tensor = next(tensor for tensor in tensor_dict.values() if tensor is not None)
    batch_size = first_tensor.shape[0]
    permutation = torch.randperm(batch_size)
    # return {key: tensor[permutation] if tensor is not None else None for key, tensor in tensor_dict.items()}

    # handle list objects
    output_dict = {}
    for key, tensor in tensor_dict.items():
        if tensor is None:
            output_dict[key] = None
            continue
        if isinstance(tensor, list):
            output_dict[key] = [tensor[i] for i in permutation]
        elif isinstance(tensor, torch.Tensor):
            output_dict[key] = tensor[permutation]
        else:
            raise ValueError(f"Unsupported tensor type: {type(tensor)} for key {key}. Expected torch.Tensor or list.")
    
    if multimodal_inputs is not None:
        permute_multimodal_inputs = {}
        for mm_key, mm_tensor in multimodal_inputs.items():
            if mm_tensor is None:
                permute_multimodal_inputs[mm_key] = None
                continue
            if isinstance(mm_tensor, list):
                permute_multimodal_inputs[mm_key] = [mm_tensor[i] for i in permutation]
            elif isinstance(mm_tensor, torch.Tensor):
                permute_multimodal_inputs[mm_key] = mm_tensor[permutation]
            else:
                raise ValueError(f"Unsupported multimodal tensor type: {type(mm_tensor)} for key {mm_key}. Expected torch.Tensor or list.")
        output_dict['multimodal_inputs'] = permute_multimodal_inputs
    
    return output_dict

